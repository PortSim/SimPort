/**
 * Starts the builder chain, from which more nodes can be attached using the DSL. Vehicles generated by the arrivals
 * node will be pushed to the next node in the chain.
 *
 * Note that if the network cannot support the traffic generated by this arrivals node, the simulation crashes, as this
 * node does not support backpressure.
 *
 * @param generator Generates the vehicles which are inserted into the network by this node.
 */
context(_: ScenarioBuilderScope)
fun <T> arrivals(label: String, generator: Generator<T>): RegularNodeBuilder<ArrivalNode<T>, T, ChannelType.Push> =
    sourceBuilder(ChannelType.Push) { ArrivalNode(label, it, generator) }

/**
 * Starts the builder chain, from which more nodes can be attached using the DSL. Vehicles generated by the arrivals
 * node will be pushed to the next node in the chain.
 *
 * If the network cannot support the traffic generated by this arrivals node, traffic would be lost and counted in a
 * dedicated sink node.
 *
 * @param generator Generates the vehicles which are inserted into the network by this node.
 */
context(_: ScenarioBuilderScope)
fun <T> arrivalsWithLoss(label: String, generator: Generator<T>): NodeBuilder<T, ChannelType.Push> {
    lateinit var output: NodeBuilder<T, ChannelType.Push>
    arrivals(label, generator)
        .thenFork(
            "$label loss fork",
            listOf({ lane1 -> output = lane1 }, { lane2 -> lane2.thenLossSink("$label loss sink") }),
            policy = forkPolicy(FirstAvailablePolicy()),
        )
    return output
}

/**
 * Attaches a delay node to the builder chain, applying a delay to all vehicles passing through the node. Vehicles that
 * has passed through the delay node are pushed to the next node in the chain.
 */
fun <T> NodeBuilder<T, *>.thenDelay(
    label: String,
    delayProvider: DelayProvider,
): RegularNodeBuilder<DelayNode<T>, T, ChannelType.Push> =
    asPush().then(ChannelType.Push) { input, output -> DelayNode(label, input, output, delayProvider) }

/**
 * Attaches a pump node to the builder chain, converting the builder chain from a pull output to a push output.
 *
 * Pump nodes are useful to connect a queue node with another node that requires an push input connection. Pump nodes do
 * not store any items.
 */
fun <T> NodeBuilder<T, ChannelType.Pull>.thenPump(
    label: String = "Pump"
): RegularNodeBuilder<PumpNode<T>, T, ChannelType.Push> =
    then(ChannelType.Push) { input, output -> PumpNode(label, input, output) }

/**
 * Attaches a fork node to the builder chain, which splits the current builder chain to `numLanes` parallel lanes, whose
 * behaviour is determined by `laneAction`. The subsequent lanes will commence with a push input connection from the
 * fork.
 *
 * When used in combination of other nodes, could construct (for example):
 * - with Join -> parallel lanes for traffic to flow through / different paths for different types of port vehicles
 * - with PushConnection -> lane for traffic to head to a previous point in the network, or to join a different network
 *   entirely.
 *
 * @param lanes List of DSL node builder chains to follow, each starting with a pull output connection from this fork
 *   node. [Read more here.](https://simport.xhirp.com/docs/tutorials/03-more-complex-port-layout.html)
 * @param policy How the fork node will decide which lane to push traffic to, when the upstream node pushes traffic into
 *   us
 */
fun <ItemT, R> NodeBuilder<ItemT, ChannelType.Push>.thenFork(
    label: String,
    lanes: List<(RegularNodeBuilder<PushForkNode<ItemT>, ItemT, ChannelType.Push>) -> R>,
    policy: ForkPolicy<ItemT> = forkPolicy(RandomPolicy()),
): List<R> {
    return thenDiverge(ChannelType.Push, lanes.size) { input, outputs -> PushForkNode(label, input, outputs, policy) }
        .zip(lanes) { node, lane -> lane(node) }
}

