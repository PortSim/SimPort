 * - with Join -> parallel lanes for traffic to flow through / different paths for different types of port vehicles
 * - with PushConnection -> lane for traffic to head to a previous point in the network, or to join a different network
 *   entirely.
 *
 * @param numLanes The number of lanes to construct with the provided `laneAction` function
 * @param policy How the fork node will decide which lane to push traffic to, when the upstream node pushes traffic into
 *   us
 * @param laneAction Function that determines the contents of each lane, depending on the lane number.
 *   [Read more here.](https://simport.xhirp.com/docs/tutorials/03-more-complex-port-layout.html)
 */
fun <ItemT, R> NodeBuilder<ItemT, ChannelType.Push>.thenFork(
    label: String,
    numLanes: Int,
    policy: ForkPolicy<ItemT> = forkPolicy(RandomPolicy()),
    laneAction: (Int, RegularNodeBuilder<PushForkNode<ItemT>, ItemT, ChannelType.Push>) -> R,
): List<R> = thenFork(label, List(numLanes) { i -> { node -> laneAction(i, node) } }, policy)

